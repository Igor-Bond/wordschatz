import { группа, тест, проверить } from '../runner.js';

/*
 * Полнота списка предварительного кэша.
 *
 * Service worker перечисляет файлы приложения поимённо. Новый модуль
 * туда добавить забывается легко, и последствия тихие: в браузере всё
 * работает, потому что файл берётся из сети, а в установленном
 * приложении без связи экран просто не открывается. Заметить это можно
 * только уйдя в самолётный режим и дойдя до нужной кнопки.
 *
 * Поэтому список сверяется не глазами, а обходом: от точки входа по
 * ссылкам import собирается всё, что приложению действительно нужно, и
 * сравнивается с перечисленным в sw.js.
 *
 * Ровно этот промах и случился с самой справкой: два новых файла
 * работали в браузере и не попали бы в кэш.
 */

/** Пути из PRECACHE_URLS. */
async function изКэша() {
    const код = await (await fetch('../sw.js')).text();
    const блок = код.match(/const PRECACHE_URLS = \[([\s\S]*?)\n\];/);

    проверить.истина(!!блок, 'в sw.js не нашёлся PRECACHE_URLS');

    return new Set(
        [...блок[1].matchAll(/'([^']+)'/g)].map(m => m[1])
    );
}

/**
 * Обход по ссылкам import от точки входа.
 *
 * Считаются и статические `from '...'`, и динамические `import('...')`:
 * второй способ у нас тоже в ходу — так подгружается Firebase.
 */
async function изИмпортов(старт = 'js/main.js') {
    const найдено = new Set();
    const очередь = [старт];

    while (очередь.length) {
        const путь = очередь.shift();
        if (найдено.has(путь)) continue;
        найдено.add(путь);

        let код;
        try {
            код = await (await fetch('../' + путь)).text();
        } catch {
            continue;
        }

        const ссылки = [
            ...код.matchAll(/\bfrom\s+'([^']+)'/g),
            ...код.matchAll(/\bimport\(\s*'([^']+)'/g)
        ];

        for (const m of ссылки) {
            const цель = m[1];
            if (!цель.startsWith('.')) continue;   // голые имена пакетов к нам не относятся

            // Разрешаем относительный путь через URL: '../core/srs.js'
            // от 'js/modules/guide.js' должен дать 'js/core/srs.js'
            const абсолютный = new URL(цель, 'https://x/' + путь).pathname.slice(1);
            if (абсолютный.startsWith('js/')) очередь.push(абсолютный);
        }
    }

    return найдено;
}

группа('Офлайн: список предварительного кэша', () => {

    тест('обход находит приложение целиком', async () => {
        // Если обход сломается, следующая проверка станет пустой и будет
        // молча проходить — эта не даёт ей стать бессмысленной
        const нужно = await изИмпортов();

        проверить.истина(нужно.size > 25, `найдено всего ${нужно.size} файлов, обход не работает`);
        проверить.истина(нужно.has('js/app.js'), 'не найден js/app.js');
        проверить.истина(нужно.has('js/core/srs.js'), 'не найден js/core/srs.js');
    });

    тест('каждый файл приложения перечислен в sw.js', async () => {
        const кэш = await изКэша();
        const нужно = await изИмпортов();

        /*
         * Конфигурация Firebase — единственное исключение. Файла может не
         * быть вовсе (приложение работает и без облака), и в кэш он
         * попадает по-своему: precache падает целиком, если хоть один
         * адрес отдаёт 404.
         */
        const кромеЭтого = new Set(['js/firebase.config.js']);

        const забытые = [...нужно].filter(п => !кэш.has(п) && !кромеЭтого.has(п));

        проверить.совпадает(забытые, [], 'файлы приложения не попали в PRECACHE_URLS');
    });

    тест('в списке нет лишних файлов', async () => {
        /*
         * Обратная сторона: переименовали модуль, а строку в sw.js
         * оставили. Установка кэша падает на первом же 404 — и падает
         * целиком, вместе с офлайном.
         *
         * Проверяется это не запросом за каждым файлом, а тем же обходом:
         * файл, до которого от точки входа не дойти, приложению не нужен,
         * даже если он ещё лежит на диске. Заодно ни одного лишнего
         * обращения к серверу — их тут и так полсотни.
         *
         * Локальный сервер, кстати, к такой проверке и не годится:
         * отсутствующий файл он подменяет главной страницей и отвечает
         * 200, как это делает правило SPA на хостинге. Ответ «файл на
         * месте» приходил бы всегда.
         */
        const кэш = await изКэша();
        const нужно = await изИмпортов();

        // Подключается статически, но своим путём — из services/auth.js,
        // и в репозитории его может не быть вовсе
        const своиПути = new Set(['js/firebase.config.js']);

        const лишние = [...кэш]
            .filter(п => п.startsWith('js/'))
            .filter(п => !нужно.has(п) && !своиПути.has(п));

        проверить.совпадает(лишние, [], 'в PRECACHE_URLS файлы, до которых приложение не доходит');
    });
});

/*
 * Кэши соседей по адресу.
 *
 * GitHub Pages раздаёт все приложения владельца с одного источника:
 * igor-bond.github.io — это и wortschatz, и трекер тренировок, и «Ноты»,
 * и шахматы. Хранилище кэшей браузер ведёт по источнику, а не по
 * каталогу, поэтому caches.keys() у нашего воркера возвращает и их кэши.
 * Стереть «все» — значит оставить соседей без офлайна, и узнаётся это
 * ровно там, где сети нет.
 *
 * Проверяется поведение, а не текст: настоящий sw.js исполняется на
 * подделанном хранилище, где рядом с нашими кэшами лежат чужие. Поиск по
 * тексту пропустил бы ту же ошибку, записанную иначе.
 */

const СОСЕДИ = ['workout-v294', 'notes-v12', 'chess-v40'];

/** Подделка CacheStorage: помнит, какие имена ещё живы. */
function подделкаКэшей() {
    const живые = new Set();

    return {
        живые,
        async keys() { return [...живые]; },
        async delete(имя) { return живые.delete(имя); },
        async open() { return { add: async () => {}, put: async () => {}, match: async () => undefined }; },
        async match() { return undefined; }
    };
}

/**
 * Настоящий sw.js на подделанном окружении.
 *
 * Воркер — обычный скрипт без импортов, поэтому исполняется как тело
 * функции, где self и caches — параметры. Имя текущего кэша берётся у
 * него же: иначе проверку пришлось бы править при каждом подъёме
 * APP_VERSION.
 */
async function загрузитьВоркер(caches) {
    const код = await (await fetch('../sw.js', { cache: 'no-store' })).text();
    const обработчики = {};

    const self = {
        addEventListener: (тип, fn) => { обработчики[тип] = fn; },
        skipWaiting: async () => {},
        clients: { claim: async () => {} },
        location: { origin: 'https://igor-bond.github.io' }
    };

    const CACHE_NAME = new Function('self', 'caches', `${код}\nreturn CACHE_NAME;`)(self, caches);
    return { обработчики, CACHE_NAME };
}

/** Событие воркера, чьё waitUntil можно дождаться. */
function событие(data) {
    const обещания = [];
    return {
        data,
        waitUntil: (p) => обещания.push(p),
        готово: () => Promise.all(обещания)
    };
}

группа('Офлайн: кэши соседей по общему адресу', () => {

    тест('активация стирает только свои прежние кэши', async () => {
        const caches = подделкаКэшей();
        const { обработчики, CACHE_NAME } = await загрузитьВоркер(caches);

        caches.живые.add(CACHE_NAME);
        caches.живые.add('wortschatz-v1');
        for (const имя of СОСЕДИ) caches.живые.add(имя);

        const e = событие();
        обработчики.activate(e);
        await e.готово();

        проверить.совпадает([...caches.живые].sort(), [CACHE_NAME, ...СОСЕДИ].sort(),
            'прошлая версия должна уйти, кэши соседей — остаться');
    });

    тест('сообщения воркеру не стирают кэши соседей', async () => {
        /*
         * Написать воркеру может любая страница источника, в том числе
         * соседская: getRegistrations() отдаёт регистрации всего адреса.
         * Поэтому неважно, шлёт ли что-то такое само приложение, — важно,
         * что воркер сделает в ответ. CLEAR_CACHES здесь потому, что такой
         * обработчик был и стирал всё подряд.
         */
        const caches = подделкаКэшей();
        const { обработчики, CACHE_NAME } = await загрузитьВоркер(caches);

        caches.живые.add(CACHE_NAME);
        for (const имя of СОСЕДИ) caches.живые.add(имя);

        for (const data of ['SKIP_WAITING', 'CLEAR_CACHES', { type: 'CLEAR_CACHES' }]) {
            const e = событие(data);
            обработчики.message?.(e);
            await e.готово();
        }

        const пропавшие = СОСЕДИ.filter((имя) => !caches.живые.has(имя));
        проверить.совпадает(пропавшие, [], 'кэши соседей удалены по сообщению');
    });
});
