import { группа, тест, проверить } from '../runner.js';
import { viewport } from '../../js/core/viewport.js';

/*
 * Разбор нижней полосы экрана.
 *
 * Эта проверка появилась после пяти заходов подряд, каждый мимо. Меню на
 * iPhone стояло вплотную к нижнему краю окна — и всё равно висело в
 * восьмидесяти точках от края дисплея, потому что окно до дисплея не
 * доходило. Числа показывали это с самого начала; читал я их неверно.
 *
 * Разница между экраном и окном сама по себе не значит ничего: на iPhone
 * это наши пиксели, на Android — системная полоса жестов. Различать их
 * по названию платформы нельзя, это совпадение, а не причина. Причина
 * читается из чисел, и вот она под проверкой.
 */

группа('Нижняя полоса: наша или системная', () => {

    // iPhone 15 Pro, встроенное приложение, строка состояния полупрозрачная
    const айфон = { экран: 852, верх: 0, окно: 793, полеСверху: 59, встроенноеIOS: true };

    // Android: те же примерно полсотни точек, но это полоса жестов
    const андроид = { экран: 800, верх: 0, окно: 745, полеСверху: 24, встроенноеIOS: false };

    тест('на iPhone полоса опознаётся по совпадению с верхним полем', () => {
        const итог = viewport.probeBottom(айфон);
        проверить.равно(итог.зазор, 59);
        проверить.истина(итог.наше, 'вычтено ровно верхнее поле — значит наше');
        проверить.равно(итог.причина, 'строка состояния');
    });

    тест('на Android такая же полоса чужая', () => {
        const итог = viewport.probeBottom(андроид);
        проверить.равно(итог.зазор, 55);
        проверить.ложь(итог.наше, 'верхнее поле 24, а полоса 55 — это не она');
        проверить.равно(итог.причина, 'системная полоса');
    });

    тест('окно вровень с экраном не даёт повода вмешиваться', () => {
        const итог = viewport.probeBottom({ экран: 852, верх: 59, окно: 793, полеСверху: 0, встроенноеIOS: true });
        проверить.равно(итог.зазор, 0);
        проверить.ложь(итог.наше);
        проверить.равно(итог.причина, 'нет');
    });

    тест('мелкие расхождения не трогаем', () => {
        // Округления и полсотни разных мелочей дают единицы точек.
        // Двигать меню из-за них — вред, это уже проходили
        const итог = viewport.probeBottom({ экран: 852, верх: 47, окно: 793, полеСверху: 12, встроенноеIOS: true });
        проверить.ложь(итог.наше, '12 точек — в пределах допуска');
        проверить.равно(итог.причина, 'нет');
    });

    тест('слишком большая разница — не наш случай', () => {
        // Safari с открытыми панелями, свёрнутое окно, что угодно ещё.
        // Строкой состояния такое не объясняется, и вслепую туда нельзя
        const итог = viewport.probeBottom({ экран: 852, верх: 0, окно: 600, полеСверху: 252, встроенноеIOS: true });
        проверить.равно(итог.зазор, 252);
        проверить.ложь(итог.наше);
        проверить.равно(итог.причина, 'чужое');
    });

    тест('в браузере на iPhone полосу не занимаем', () => {
        // Те же числа, но приложение открыто вкладкой: под окном панели
        // Safari, и меню, опущенное туда, просто уедет под них
        const итог = viewport.probeBottom({ ...айфон, встроенноеIOS: false });
        проверить.ложь(итог.наше);
        проверить.равно(итог.причина, 'системная полоса');
    });

    тест('совпадение с полем допускает округление в пару точек', () => {
        // iOS отдаёт поля дробными, и точного равенства ждать нельзя
        проверить.истина(viewport.probeBottom({ ...айфон, полеСверху: 58 }).наше, 'на точку меньше');
        проверить.истина(viewport.probeBottom({ ...айфон, полеСверху: 61 }).наше, 'на две больше');
        проверить.ложь(viewport.probeBottom({ ...айфон, полеСверху: 34 }).наше, 'а вот это уже другое поле');
    });

    тест('нулевое верхнее поле ничего не подтверждает', () => {
        // Без поля совпадать не с чем, и утверждать, что полоса наша,
        // не на чем — остаёмся на безопасной стороне
        проверить.ложь(viewport.probeBottom({ ...айфон, полеСверху: 0 }).наше);
    });

    тест('высота экрана неизвестна — не выдумываем', () => {
        const итог = viewport.probeBottom({ экран: 0, верх: 0, окно: 793, полеСверху: 59, встроенноеIOS: true });
        проверить.равно(итог.зазор, 0, 'отрицательную разницу за зазор не выдаём');
        проверить.ложь(итог.наше);
    });

    тест('окно, сдвинутое вниз, полосы под собой не оставляет', () => {
        // Так выглядит iPhone после переустановки значка с меткой black:
        // окно начинается под строкой состояния и доходит до низа
        const итог = viewport.probeBottom({ экран: 852, верх: 59, окно: 793, полеСверху: 59, встроенноеIOS: true });
        проверить.равно(итог.зазор, 0);
        проверить.ложь(итог.наше, 'чинить нечего — сдвиг снимется сам');
    });
});
