import { группа, тест, проверить } from '../runner.js';

/*
 * Числа в документах сверяются с действительностью.
 *
 * Раньше они переписывались руками в три места и врали во всех трёх:
 * `QA.md` называл крупнейшим модулем `exercises.js` на 972 строки, когда
 * тот успел вырасти до 1277, а потом и вовсе был разделён; счёт проверок
 * я сам однажды записал как «в 20 наборах», когда их было 19.
 *
 * Теперь числа живут в одном месте, `docs/NUMBERS.md`, и пересчитываются
 * скриптом `tools/stats.ps1`. Скрипт запускают руками — значит, забыть
 * его тоже можно. Эта проверка и есть напоминание: она пересчитывает всё
 * заново и падает, если таблица отстала.
 *
 * Вторая половина следит, чтобы числа не расползлись обратно по другим
 * документам: единственный источник перестаёт быть единственным ровно в
 * тот момент, когда кто-то из вежливости повторит цифру в соседнем файле.
 */

/** Таблица из NUMBERS.md: { 'Модулей JS': '53', ... } */
async function изТаблицы() {
    const текст = await (await fetch('../docs/NUMBERS.md')).text();
    const блок = текст.match(/<!-- НАЧАЛО ЧИСЕЛ -->([\s\S]*?)<!-- КОНЕЦ ЧИСЕЛ -->/);

    проверить.истина(!!блок, 'в docs/NUMBERS.md не нашлись метки таблицы');

    const строки = {};
    for (const строка of блок[1].split('\n')) {
        const m = строка.match(/^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|$/);
        if (!m || m[1].startsWith('---') || m[1] === 'Показатель') continue;
        строки[m[1]] = m[2];
    }
    return строки;
}

/** Все файлы приложения — берём список из sw.js, он проверен отдельно. */
async function файлыПриложения() {
    const sw = await (await fetch('../sw.js')).text();
    const блок = sw.match(/const PRECACHE_URLS = \[([\s\S]*?)\n\];/)[1];
    return [...блок.matchAll(/'([^']+)'/g)].map(m => m[1]).filter(p => p.startsWith('js/') && p.endsWith('.js'));
}

/**
 * Строк в файле — так же, как их считает Get-Content в скрипте:
 * последняя строка без перевода в конце тоже считается.
 */
function строк(текст) {
    if (!текст) return 0;
    return текст.replace(/\r\n/g, '\n').replace(/\n$/, '').split('\n').length;
}

группа('Числа в документах', () => {

    тест('в таблице все пять показателей', async () => {
        const т = await изТаблицы();
        for (const ключ of ['Модулей JS', 'Строк своего JavaScript', 'Крупнейший модуль',
                            'Автоматических проверок', 'Наборов проверок']) {
            проверить.истина(ключ in т, `нет строки «${ключ}»`);
        }
    });

    тест('модулей, строк и крупнейший — как на диске', async () => {
        const т = await изТаблицы();
        const пути = await файлыПриложения();

        let всего = 0;
        let крупнейший = { путь: '', строк: 0 };

        for (const путь of пути) {
            const текст = await (await fetch('../' + путь)).text();
            const н = строк(текст);
            всего += н;
            if (н > крупнейший.строк) крупнейший = { путь: путь.slice(3), строк: н };
        }

        проверить.равно(Number(т['Модулей JS']), пути.length, 'число модулей отстало — прогоните tools/stats.ps1');
        проверить.равно(Number(т['Строк своего JavaScript']), всего, 'число строк отстало — прогоните tools/stats.ps1');
        проверить.равно(т['Крупнейший модуль'], `${крупнейший.путь}, ${крупнейший.строк}`,
            'крупнейший модуль отстал — прогоните tools/stats.ps1');
    });

    тест('проверок и наборов — сколько их на самом деле', async () => {
        const т = await изТаблицы();

        const индекс = await (await fetch('../tests/index.html')).text();
        const наборы = [...индекс.matchAll(/\.\/suites\/([\w.-]+\.test\.js)/g)].map(m => m[1]);

        проверить.истина(наборы.length > 0, 'список наборов не прочитался');

        let проверок = 0;
        for (const набор of наборы) {
            const текст = await (await fetch('../tests/suites/' + набор)).text();
            // Без \b: в JavaScript граница слова определена через \w, то
            // есть [A-Za-z0-9_], и перед кириллической «т» её попросту
            // нет — образец не совпал бы никогда, а счёт молча вышел бы
            // нулевым. Тот же капкан уже ловил подстановки в справке.
            проверок += (текст.match(/тест\(/g) || []).length;
        }

        проверить.равно(Number(т['Наборов проверок']), наборы.length, 'число наборов отстало — прогоните tools/stats.ps1');
        проверить.равно(Number(т['Автоматических проверок']), проверок, 'число проверок отстало — прогоните tools/stats.ps1');
    });

    тест('другие документы чисел не повторяют', async () => {
        /*
         * Единственный источник перестаёт быть единственным в тот момент,
         * когда цифру из вежливости повторят в соседнем файле. Ищем
         * именно повторы показателей, а не любые числа: даты, версии,
         * замеры времени и веса остаются где были.
         *
         * README и STATUS ссылаются на NUMBERS.md словами, без цифр.
         */
        const документы = ['README.md', 'docs/STATUS.md', 'docs/QA.md', 'docs/REPORT.md'];
        /*
         * Ищется число рядом с показателем, а не сам показатель:
         * заголовок «Модулей JS» в строке, которая отсылает к
         * NUMBERS.md, — это ссылка, а не повтор. Первая редакция
         * проверки этого не различала и ругалась на собственную же
         * замену.
         */
        const образцы = [
            /\d+\s+пров[её]рок/i,
            /\d+\s+наборах/i,
            /\d+\s+файлов\s+JS/i,
            /\d[\d\s]*строк\s+своего/i,
            /Модулей JS\s*\|\s*\d/
        ];

        const попались = [];
        for (const документ of документы) {
            const текст = await (await fetch('../' + документ)).text();
            for (const образец of образцы) {
                const m = текст.match(образец);
                if (m) попались.push(`${документ}: «${m[0].trim()}»`);
            }
        }

        проверить.совпадает(попались, [], 'числа снова переписаны в другие документы — место им в docs/NUMBERS.md');
    });
});
