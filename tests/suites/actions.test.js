import { группа, тест, проверить } from '../runner.js';
import { actions } from '../../js/core/actions.js';

группа('Значения в data-атрибутах', () => {

    тест('апостроф проходит как есть', () => {
        // Ради этого всё и затевалось: раньше апостроф попадал в код
        // обработчика и ломал разметку — «geht's», «м'ясо», «O'Neill»
        проверить.равно(actions.attr("geht's"), "geht's");
        проверить.равно(actions.attr("O'Neill"), "O'Neill");
        проверить.равно(actions.attr("м'ясо"), "м'ясо");
    });

    тест('кавычка закрыла бы атрибут — экранируется', () => {
        проверить.равно(actions.attr('он сказал "да"'), 'он сказал &quot;да&quot;');
    });

    тест('угловые скобки и амперсанд', () => {
        проверить.равно(actions.attr('<b>'), '&lt;b&gt;');
        проверить.равно(actions.attr('Tisch & Stuhl'), 'Tisch &amp; Stuhl');
    });

    тест('амперсанд экранируется первым', () => {
        // Иначе &quot; из кавычки превратился бы в &amp;quot;
        проверить.равно(actions.attr('&"'), '&amp;&quot;');
    });

    тест('попытка закрыть атрибут и добавить свой обработчик', () => {
        const итог = actions.attr('" onmouseover="alert(1)');
        проверить.ложь(итог.includes('"'), 'кавычек не остаётся');
        проверить.равно(итог, '&quot; onmouseover=&quot;alert(1)');
    });

    тест('пустое значение не даёт undefined', () => {
        проверить.равно(actions.attr(null), '');
        проверить.равно(actions.attr(undefined), '');
        проверить.равно(actions.attr(''), '');
    });

    тест('числа приводятся к строке', () => {
        проверить.равно(actions.attr(42), '42');
        проверить.равно(actions.attr(0), '0');
    });

    тест('после разбора браузером значение возвращается целым', () => {
        // Главная проверка: что записали, то и прочитается из dataset.
        // Прежние способы этого не выдерживали — HTML-сущность браузер
        // раскодировал до разбора кода, и апостроф ломал обработчик
        for (const исходник of ["geht's", 'он сказал "да"', '<b>', 'Tisch & Stuhl', "м'ясо & сім'я"]) {
            const div = document.createElement('div');
            div.innerHTML = `<button data-value="${actions.attr(исходник)}"></button>`;
            проверить.равно(div.firstElementChild.dataset.value, исходник, исходник);
        }
    });
});
