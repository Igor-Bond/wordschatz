import { группа, тест, проверить } from '../runner.js';
import { quiz } from '../../js/core/quiz.js';

const пул = [
    { id: 1, word: 'der Tisch', translation: 'стол', type: 'noun', topic: 'Мебель' },
    { id: 2, word: 'der Stuhl', translation: 'стул', type: 'noun', topic: 'Мебель' },
    { id: 3, word: 'das Bett', translation: 'кровать', type: 'noun', topic: 'Мебель' },
    { id: 4, word: 'die Lampe', translation: 'лампа', type: 'noun', topic: 'Свет' },
    { id: 5, word: 'nehmen', translation: 'брать', type: 'verb', topic: 'Действия' },
    { id: 6, word: 'geben', translation: 'давать', type: 'verb', topic: 'Действия' },
    { id: 7, word: 'hell', translation: 'светлый', type: 'adjective', topic: 'Свет' }
];

группа('Варианты ответа', () => {

    тест('перемешивание сохраняет состав', () => {
        const исходный = [1, 2, 3, 4, 5];
        const результат = quiz.shuffle(исходный);
        проверить.равно(результат.length, 5);
        проверить.совпадает([...результат].sort(), [1, 2, 3, 4, 5]);
    });

    тест('перемешивание не портит исходный массив', () => {
        const исходный = [1, 2, 3, 4, 5];
        quiz.shuffle(исходный);
        проверить.совпадает(исходный, [1, 2, 3, 4, 5]);
    });

    тест('дистракторы не содержат само слово', () => {
        for (let i = 0; i < 20; i++) {
            const d = quiz.pickDistractors(пул[0], пул, 3);
            проверить.ложь(d.some(w => w.id === пул[0].id), 'загаданное слово попало в неверные варианты');
        }
    });

    тест('дистракторы той же части речи, когда их хватает', () => {
        // Иначе вариант выбирался по грамматике, без знания слова
        for (let i = 0; i < 20; i++) {
            const d = quiz.pickDistractors(пул[0], пул, 3);
            проверить.истина(d.every(w => w.type === 'noun'), 'к существительному подмешались другие части речи');
        }
    });

    тест('своя тема предпочитается чужой', () => {
        // «стол» рядом со «стулом» и «кроватью» — задание про мебель,
        // а не про случайный набор слов
        for (let i = 0; i < 20; i++) {
            const d = quiz.pickDistractors(пул[0], пул, 2);
            проверить.истина(d.every(w => w.topic === 'Мебель'), 'взяты слова чужой темы при наличии своей');
        }
    });

    тест('при нехватке своей части речи берутся любые слова', () => {
        // Оставить человека без задания хуже, чем показать вариант
        // другой части речи: глаголов в пуле всего два
        const d = quiz.pickDistractors(пул[4], пул, 3);
        проверить.равно(d.length, 3, 'запрошенное количество должно набраться');
        проверить.истина(d.some(w => w.type !== 'verb'), 'без подмешивания трёх вариантов не набрать');
    });

    тест('дистракторы не повторяют перевод', () => {
        const сДублем = [...пул, { id: 8, word: 'die Tafel', translation: 'стол', type: 'noun' }];
        for (let i = 0; i < 20; i++) {
            const d = quiz.pickDistractors(сДублем[0], сДублем, 3);
            проверить.ложь(d.some(w => w.translation === 'стол'), 'вариант с тем же переводом делает задание нерешаемым');
        }
    });

    тест('запрошенное количество соблюдается', () => {
        проверить.равно(quiz.pickDistractors(пул[0], пул, 3).length, 3);
        проверить.равно(quiz.pickDistractors(пул[0], пул, 2).length, 2);
    });

    тест('маленький пул не ломает выбор', () => {
        const d = quiz.pickDistractors(пул[0], [пул[0], пул[1]], 3);
        проверить.истина(d.length <= 1, 'из двух слов больше одного неверного варианта не составить');
    });

    тест('в вариантах ответа есть правильный', () => {
        for (let i = 0; i < 20; i++) {
            const options = quiz.buildOptions(пул[0], пул, 3);
            проверить.истина(options.some(w => w.id === пул[0].id), 'правильный ответ пропал из вариантов');
            проверить.равно(options.length, 4);
        }
    });

    тест('позиция правильного ответа не закреплена', () => {
        // Если правильный всегда первый, задание решается без чтения
        const позиции = new Set();
        for (let i = 0; i < 40; i++) {
            позиции.add(quiz.buildOptions(пул[0], пул, 3).findIndex(w => w.id === пул[0].id));
        }
        проверить.истина(позиции.size > 1, 'правильный ответ всегда оказывается на одном месте');
    });
});
