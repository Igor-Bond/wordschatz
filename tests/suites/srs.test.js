import { группа, тест, проверить } from '../runner.js';
import { srs } from '../../js/core/srs.js';

const новое = () => ({ interval: 0, ease: 2.5, repetitions: 0, phase: 'learning', stepIndex: 0 });

/** Прогон цепочки оценок: возвращает состояние слова после всех ответов. */
const прогнать = (оценки, start = новое()) => {
    let word = { ...start };
    for (const q of оценки) {
        const r = srs.calculate(q, word);
        word = { ...word, ...r, repetitions: (word.repetitions || 0) + 1 };
    }
    return word;
};

группа('Интервальное повторение', () => {

    тест('новое слово начинает с фазы заучивания', () => {
        const w = прогнать([3]);
        проверить.равно(w.phase, 'learning');
        проверить.равно(w.interval, 0, 'первый шаг — минуты, а не дни');
    });

    тест('после шагов заучивания слово выходит на дни', () => {
        const w = прогнать([3, 3]);
        проверить.равно(w.phase, 'review');
        проверить.вПределах(w.interval, 1, 2);
    });

    тест('интервал растёт от повторения к повторению', () => {
        const a = прогнать([3, 3]);
        const b = прогнать([3, 3, 3]);
        проверить.истина(b.interval > a.interval, 'третье «Хорошо» должно дать интервал больше второго');
    });

    тест('«Легко» увеличивает лёгкость, «Трудно» уменьшает', () => {
        const легко = прогнать([3, 3, 4]);
        const трудно = прогнать([3, 3, 2]);
        проверить.истина(легко.ease > 2.5, 'после «Легко» лёгкость должна вырасти');
        проверить.истина(трудно.ease < 2.5, 'после «Трудно» лёгкость должна упасть');
    });

    тест('«Снова» возвращает слово в заучивание', () => {
        const w = прогнать([3, 3, 3, 1]);
        проверить.равно(w.phase, 'learning');
    });

    тест('лёгкость не падает ниже 1.3', () => {
        // Двадцать провалов подряд: без ограничителя интервалы схлопнулись бы
        const w = прогнать(Array(20).fill(1));
        проверить.истина(w.ease >= 1.3, `лёгкость ушла ниже предела: ${w.ease}`);
    });

    тест('лёгкость не растёт выше 3.0', () => {
        const w = прогнать(Array(30).fill(4));
        проверить.истина(w.ease <= 3.0, `лёгкость превысила предел: ${w.ease}`);
    });

    тест('интервал не превышает года', () => {
        const w = прогнать(Array(40).fill(4));
        проверить.истина(w.interval <= 365, `интервал больше года: ${w.interval}`);
    });

    тест('разброс интервала не выходит за пять процентов', () => {
        // Разброс нужен, чтобы слова одного дня не всплывали кучей.
        // Проверяем, что он остаётся разбросом, а не переносом
        const базовое = { interval: 100, ease: 2.5, repetitions: 5, phase: 'review', stepIndex: 0 };
        for (let i = 0; i < 50; i++) {
            const r = srs.calculate(3, базовое);
            проверить.вПределах(r.interval, 100 * 2.5 * 0.94, 100 * 2.5 * 1.06);
        }
    });

    тест('срок следующего показа лежит в будущем', () => {
        const r = srs.calculate(3, { interval: 3, ease: 2.5, repetitions: 3, phase: 'review', stepIndex: 0 });
        проверить.истина(r.nextReview > Date.now(), 'nextReview должен быть впереди');
    });
});

/*
 * Ошибка на контроле темы.
 *
 * Контроль долго был термометром: он замечал забытое слово — освоенность
 * падала, — но срок повторения не трогал. Слово с интервалом в три
 * недели, проваленное на контроле, возвращалось всё равно через три
 * недели, хотя приложение уже знало, что оно забыто.
 */
группа('Провал на контроле возвращает слово в повторение', () => {

    const ДЕНЬ = 24 * 60 * 60 * 1000;
    const зрелое = () => ({
        interval: 21, ease: 2.5, phase: 'review', stepIndex: 0,
        repetitions: 8, nextReview: Date.now() + 21 * ДЕНЬ
    });

    тест('срок переносится на завтра, а не на три недели', () => {
        const слово = зрелое();
        srs.applyExamLapse(слово);

        const через = (слово.nextReview - Date.now()) / ДЕНЬ;
        проверить.вПределах(через, 0.9, 1.1, 'слово должно вернуться завтра');
    });

    тест('считается обычным провалом: интервал вдвое, лёгкость вниз', () => {
        const слово = зрелое();
        srs.applyExamLapse(слово);

        проверить.равно(слово.interval, 11, 'интервал должен ополовиниться');
        проверить.равно(слово.ease, 2.3, 'лёгкость должна просесть на 0,2');
        проверить.равно(слово.phase, 'learning', 'слово должно вернуться в заучивание');
        проверить.равно(слово.stepIndex, 0);
    });

    тест('счётчик повторений не растёт', () => {
        // Контроль — не повторение, а по этому счётчику выбирается
        // ступень заданий: засчитав его, мы подняли бы слово на ступень
        // ровно за то, что человек его забыл
        const слово = зрелое();
        srs.applyExamLapse(слово);

        проверить.равно(слово.repetitions, 8);
    });

    тест('не зовёт в тот же день, в отличие от провала в уроке', () => {
        /*
         * Обычный провал зовёт через десять минут: он случается посреди
         * урока, и человек тут же продолжает. Контроль на этом
         * заканчивается — звать в тот же день некуда.
         */
        const вУроке = srs.calculate(1, зрелое());
        const наКонтроле = srs.applyExamLapse(зрелое());

        const минутВУроке = (вУроке.nextReview - Date.now()) / 60000;
        проверить.вПределах(минутВУроке, 9, 11, 'провал в уроке зовёт через десять минут');
        проверить.истина(наКонтроле.nextReview > вУроке.nextReview, 'контроль должен звать позже');
    });
});

/*
 * Четыре кнопки обещают четыре разных срока.
 *
 * Сообщено владельцем: на плашках разного цвета иногда написано одно и
 * то же время — «1 день» на обеих средних. Замер подтвердил: восемнадцать
 * совпадений на тысячу четыреста сочетаний интервала и лёгкости.
 *
 * И это была не описка в подписи. Формулы разные — ×1,2, ×лёгкость и
 * ×лёгкость×1,3, — но после округления до целых дней при малом интервале
 * они давали одно число, и сроки действительно совпадали. Две кнопки
 * делали ровно одно и то же.
 */
группа('Сроки на четырёх кнопках не схлопываются', () => {

    /** Разброс мешает сравнивать формулы — на время проверок снимаем. */
    const безРазброса = (тело) => {
        const прежний = srs.applyFuzz;
        srs.applyFuzz = (d) => d;
        try { return тело(); } finally { srs.applyFuzz = прежний; }
    };

    тест('в повторении все три срока строго по возрастанию', () => {
        безРазброса(() => {
            const совпавшие = [];

            for (let interval = 1; interval <= 60; interval++) {
                for (let e = 130; e <= 300; e += 5) {
                    const слово = { interval, ease: e / 100, phase: 'review', stepIndex: 0, repetitions: 5 };
                    const т = srs.calculate(2, слово).interval;
                    const х = srs.calculate(3, слово).interval;
                    const л = srs.calculate(4, слово).interval;

                    if (!(т < х && х < л)) совпавшие.push(`интервал ${interval}, лёгкость ${e / 100}: ${т}/${х}/${л}`);
                }
            }

            проверить.совпадает(совпавшие.slice(0, 5), [], 'сроки схлопнулись или пошли не по порядку');
        });
    });

    тест('«Хорошо» всегда удлиняет интервал', () => {
        /*
         * При лёгкости у самого дна 1 × 1,3 округлялось обратно в 1:
         * слово возвращалось каждый день, сколько ни отвечай верно.
         */
        безРазброса(() => {
            const застрявшие = [];

            for (let interval = 1; interval <= 60; interval++) {
                for (let e = 130; e <= 300; e += 5) {
                    const слово = { interval, ease: e / 100, phase: 'review', stepIndex: 0, repetitions: 5 };
                    const х = srs.calculate(3, слово).interval;
                    if (х <= interval) застрявшие.push(`интервал ${interval}, лёгкость ${e / 100} → ${х}`);
                }
            }

            проверить.совпадает(застрявшие.slice(0, 5), [], 'верный ответ не удлинил интервал');
        });
    });

    тест('подписи на кнопках различаются и в заучивании', () => {
        // Там сроки считаются иначе — шагами, а не умножением, — и
        // проверять их надо отдельно
        безРазброса(() => {
            const одинаковые = [];

            for (const stepIndex of [0, 1]) {
                for (let e = 130; e <= 300; e += 10) {
                    const слово = { interval: 0, ease: e / 100, phase: 'learning', stepIndex, repetitions: stepIndex };
                    const подписи = [1, 2, 3, 4].map(q => srs.describeNext(q, слово));

                    if (new Set(подписи).size < 4) одинаковые.push(`шаг ${stepIndex}, лёгкость ${e / 100}: ${подписи.join(' / ')}`);
                }
            }

            проверить.совпадает(одинаковые, [], 'на кнопках одинаковые подписи');
        });
    });

    тест('слабое слово: 10 мин, 1 день, 2 дня, 3 дня', () => {
        // Тот самый случай из жалобы: интервал 1, лёгкость у дна
        безРазброса(() => {
            const слабое = { interval: 1, ease: 1.3, phase: 'review', stepIndex: 0, repetitions: 5 };
            const подписи = [1, 2, 3, 4].map(q => srs.describeNext(q, слабое));

            проверить.равно(new Set(подписи).size, 4, `подписи повторяются: ${подписи.join(' / ')}`);
        });
    });

    тест('там, где числа и так расходились, ничего не сдвинулось', () => {
        // Правка обязана поднимать срок только при схлопывании.
        // Обычное зрелое слово должно считаться ровно как раньше
        безРазброса(() => {
            const зрелое = { interval: 20, ease: 2.5, phase: 'review', stepIndex: 0, repetitions: 9 };

            проверить.равно(srs.calculate(2, зрелое).interval, 24, 'Трудно: 20 × 1,2');
            проверить.равно(srs.calculate(3, зрелое).interval, 50, 'Хорошо: 20 × 2,5');
            проверить.равно(srs.calculate(4, зрелое).interval, 69, 'Легко: 20 × 2,65 × 1,3');
        });
    });
});
