import { группа, тест, проверить } from '../runner.js';
import { sync } from '../../js/services/sync.js';

/*
 * Проверяется решающая часть обмена, без сети: кого считать свежее,
 * что отправлять и как это резать на пачки. Именно здесь ошибка тихо
 * теряет правку или удваивает расход бесплатной квоты.
 */

группа('Разрешение конфликтов при обмене', () => {

    тест('свежая запись из облака побеждает', () => {
        проверить.истина(sync.remoteWins({ updatedAt: 100 }, { updatedAt: 200 }));
    });

    тест('устаревшая запись из облака не принимается', () => {
        проверить.ложь(sync.remoteWins({ updatedAt: 200 }, { updatedAt: 100 }));
    });

    тест('при равных метках побеждает местная', () => {
        // Строгое сравнение: одинаковое время — это чаще всего та же
        // запись, и переписывать её незачем
        проверить.ложь(sync.remoteWins({ updatedAt: 100 }, { updatedAt: 100 }));
    });

    тест('незнакомая запись принимается всегда', () => {
        проверить.истина(sync.remoteWins(undefined, { updatedAt: 1 }));
        проверить.истина(sync.remoteWins(null, { updatedAt: 0 }));
    });

    тест('запись без метки считается древней', () => {
        проверить.истина(sync.remoteWins({}, { updatedAt: 1 }), 'местная без метки уступает');
        проверить.ложь(sync.remoteWins({ updatedAt: 1 }, {}), 'облачная без метки не побеждает');
    });

    тест('удаление доезжает как обычная запись', () => {
        // Мягкое удаление на то и мягкое: строка с deletedAt свежее той,
        // что без него, и должна вытеснить её на другом устройстве
        const местная = { id: 5, word: 'der Tisch', updatedAt: 100 };
        const облачная = { id: 5, word: 'der Tisch', updatedAt: 200, deletedAt: 200 };
        проверить.истина(sync.remoteWins(местная, облачная));
    });

    тест('удаление не воскрешается старой копией', () => {
        const местная = { id: 5, updatedAt: 200, deletedAt: 200 };
        const облачная = { id: 5, updatedAt: 100 };
        проверить.ложь(sync.remoteWins(местная, облачная));
    });
});

группа('Что уходит в облако', () => {

    const строки = [
        { id: 1, updatedAt: 50 },
        { id: 2, updatedAt: 150 },
        { id: 3, updatedAt: 250 },
        { id: 4 }
    ];

    тест('отправляем только изменившееся после отметки', () => {
        const итог = sync.changedSince(строки, 100);
        проверить.равно(итог.length, 2);
        проверить.равно(итог.map(r => r.id).join(','), '2,3');
    });

    тест('запись без метки не отправляется', () => {
        проверить.ложь(sync.changedSince(строки, 0).some(r => r.id === 4));
    });

    тест('граница строгая: ровно на отметке не отправляем', () => {
        проверить.ложь(sync.changedSince(строки, 150).some(r => r.id === 2));
    });

    тест('только что принятое из облака обратно не уходит', () => {
        // Иначе каждая принятая запись тем же обменом улетала назад
        // с тем же updatedAt: расход записей Firestore вдвое
        const принятые = new Set(['2', '3']);
        проверить.равно(sync.changedSince(строки, 100, принятые).length, 0);
    });

    тест('местная правка уходит, даже если сосед пришёл из облака', () => {
        const принятые = new Set(['2']);
        const итог = sync.changedSince(строки, 100, принятые);
        проверить.равно(итог.map(r => r.id).join(','), '3');
    });

    тест('ключ записи — строка, как в облаке', () => {
        проверить.равно(sync.rowKey({ id: 42 }), '42');
        проверить.равно(sync.rowKey({ id: '42' }), '42', 'число и строка — один документ');
    });
});

