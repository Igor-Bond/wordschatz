import { группа, тест, проверить } from '../runner.js';

const { scheduler } = await import('../../js/core/scheduler.js');
const { srs } = await import('../../js/core/srs.js');
const { exercises } = await import('../../js/modules/exercises.js');

/*
 * Нагрузка и темп: сколько человек в состоянии унести за день.
 *
 * Три правила отсюда появились после разбора арифметики расписания, и
 * все три раньше были заданы «на глаз»: потолок повторений, снижение
 * нормы при перегрузке и то, чей ответ двигает сроки.
 */

группа('Потолок повторений покрывает зрелую нагрузку', () => {

    /*
     * Откуда берётся множитель восемь.
     *
     * Интервалы растут как 1, 3, 8, 20, 50, 125, 313 дней. Карточек с
     * интервалом I накапливается I×норма, и каждая просит повторения раз
     * в I дней — значит каждая ступень даёт ровно «норму» повторений в
     * день, сколько бы ни был велик сам интервал. Ступеней к году семь,
     * дальше восемь.
     *
     * Потолок стоял на пяти нормах, то есть ниже зрелой нагрузки на
     * треть. Долг набегал ежедневно и не рассасывался никогда.
     */

    /** Сколько повторений в день созревает к возрасту словаря. */
    const зрелаяНагрузка = (норма, деньСНачала) => {
        const интервалы = [1, 3, 8, 20, 50, 125, 313, 365];
        let возраст = 0;
        let ступеней = 0;

        for (const и of интервалы) {
            if (возраст > деньСНачала) break;
            ступеней++;
            возраст += и;
        }
        return норма * ступеней;
    };

    тест('к году потолок не ниже созревающей нагрузки', () => {
        for (const норма of scheduler.GOAL_STEPS) {
            const нагрузка = зрелаяНагрузка(норма, 365);
            проверить.истина(
                scheduler.getReviewLimit(норма) >= нагрузка,
                `норма ${норма}: потолок ${scheduler.getReviewLimit(норма)} против нагрузки ${нагрузка}`
            );
        }
    });

    тест('прежний множитель пять зрелую нагрузку не покрывал', () => {
        // Проверка держит вывод, ради которого потолок и меняли
        проверить.истина(10 * 5 < зрелаяНагрузка(10, 365), 'при норме 10 старый потолок был мал');
    });

    тест('маленькая норма всё равно даёт рабочий минимум', () => {
        проверить.истина(scheduler.getReviewLimit(1) >= 30, 'словарь из десятка слов не должен буксовать');
    });
});

группа('Норма снижается, когда повторения не помещаются', () => {

    тест('два дня перегрузки терпим', () => {
        let состояние = { postponed: 12, goal: 10, streak: 0 };
        const первый = scheduler.overloadDecision(состояние);
        проверить.равно(первый.streak, 1);
        проверить.равно(первый.lowered, null);

        const второй = scheduler.overloadDecision({ ...состояние, streak: первый.streak });
        проверить.равно(второй.streak, 2);
        проверить.равно(второй.lowered, null, 'разовый завал — не повод менять норму');
    });

    тест('на третий снижаем на ступень', () => {
        const итог = scheduler.overloadDecision({ postponed: 12, goal: 10, streak: 2 });
        проверить.равно(итог.goal, 5);
        проверить.равно(итог.lowered.from, 10);
        проверить.равно(итог.lowered.to, 5);
        проверить.равно(итог.streak, 0, 'счётчик обнуляется — новой норме дают шанс');
    });

    тест('день без переносов сбрасывает счёт', () => {
        const итог = scheduler.overloadDecision({ postponed: 0, goal: 10, streak: 2 });
        проверить.равно(итог.streak, 0);
        проверить.равно(итог.lowered, null);
    });

    тест('норма идёт по ступеням настроек, а не произвольно', () => {
        проверить.равно(scheduler.lowerGoal(20), 15);
        проверить.равно(scheduler.lowerGoal(15), 10);
        проверить.равно(scheduler.lowerGoal(10), 5);
    });

    тест('ниже нижней ступени не опускаемся', () => {
        // На пяти словах в день дело уже не в норме, и отнимать
        // последнее — значит отнять смысл заниматься
        const итог = scheduler.overloadDecision({ postponed: 30, goal: 5, streak: 5 });
        проверить.равно(итог.goal, 5);
        проверить.равно(итог.lowered, null);
    });

    тест('сама вверх норма не растёт', () => {
        // Поднимать нагрузку человек решает сам. Иначе одна удачная
        // неделя вернула бы его туда, откуда только что спустили
        const итог = scheduler.overloadDecision({ postponed: 0, goal: 5, streak: 0 });
        проверить.равно(итог.goal, 5);
    });
});

группа('Ответ в упражнении двигает расписание', () => {

    тест('перенос расчёта в слово считает повторение состоявшимся', () => {
        const слово = { interval: 10, ease: 2.5, phase: 'review', repetitions: 4, status: 'pending' };
        srs.applyTo(слово, 3);

        проверить.истина(слово.interval > 10, 'интервал вырос');
        проверить.равно(слово.repetitions, 5, 'повторение засчитано');
        проверить.равно(слово.status, 'learning', 'слово больше не ждёт своего дня');
        проверить.истина(слово.nextReview > Date.now(), 'срок в будущем');
    });

    тест('неверный ответ возвращает слово в заучивание', () => {
        const слово = { interval: 20, ease: 2.5, phase: 'review', repetitions: 6 };
        srs.applyTo(слово, 1);

        проверить.равно(слово.phase, 'learning');
        проверить.истина(слово.interval < 20, 'интервал урезан, но не обнулён');
        проверить.истина(слово.interval > 0);
    });

    тест('расписание двигают только слова урока', () => {
        // Свободная тренировка и экзамен спрашивают слово вне очереди:
        // сдвигать от этого сроки нельзя, иначе повторениями можно было
        // бы управлять в обход расписания
        exercises.schedulingIds = new Set([7]);
        exercises.exam = null;
        exercises.isRoomMode = false;
        проверить.истина(exercises._movesSchedule({ id: 7 }), 'слово из очереди урока');
        проверить.ложь(exercises._movesSchedule({ id: 8 }), 'чужое слово');

        exercises.isRoomMode = true;
        проверить.ложь(exercises._movesSchedule({ id: 7 }), 'свободная тренировка');

        exercises.isRoomMode = false;
        exercises.exam = { title: 'проверка', onAnswer: () => {} };
        проверить.ложь(exercises._movesSchedule({ id: 7 }), 'экзамен');

        exercises.exam = null;
        exercises.schedulingIds = null;
        проверить.ложь(exercises._movesSchedule({ id: 7 }), 'список не задан');
    });
});

группа('Одно извлечение на слово за урок', () => {

    /*
     * Раньше слово проходило урок дважды: карточка, через несколько
     * минут упражнение. Второе извлечение шло почти сразу за первым и
     * прочности не добавляло, а половину урока съедало.
     */

    const урок = (повторение, новые) => {
        const поКарточке = повторение.filter(w => exercises.getStage(w) === 'recognition');
        const поЗаданию = повторение.filter(w => exercises.getStage(w) !== 'recognition');
        return {
            карточки: [...поКарточке, ...новые].length,
            упражнения: [...поЗаданию, ...новые].length
        };
    };

    const узнавание = { repetitions: 1, mastery: 10 };
    const закрепление = { repetitions: 5, mastery: 45 };
    const воспроизведение = { repetitions: 9, mastery: 80 };
    const новое = { repetitions: 0, mastery: 0 };

    тест('повторяемое слово проходит урок один раз', () => {
        проверить.равно(экземпляров(урок([узнавание], [])), 1, 'узнавание — только карточка');
        проверить.равно(экземпляров(урок([закрепление], [])), 1, 'закрепление — только упражнение');
        проверить.равно(экземпляров(урок([воспроизведение], [])), 1, 'воспроизведение — только упражнение');
    });

    тест('новое слово проходит дважды, и это не повтор', () => {
        // Карточка показывает, упражнение спрашивает в первый раз
        проверить.равно(экземпляров(урок([], [новое])), 2);
    });

    тест('урок сокращается почти вдвое', () => {
        const повторение = [узнавание, закрепление, закрепление, воспроизведение, воспроизведение];
        const новые = [новое, новое];

        const было = (повторение.length + новые.length) * 2;
        const стало = экземпляров(урок(повторение, новые));

        проверить.равно(было, 14);
        проверить.равно(стало, 9);
        проверить.истина(стало < было * 0.7, `${было} → ${стало}`);
    });

    function экземпляров(итог) {
        return итог.карточки + итог.упражнения;
    }
});
