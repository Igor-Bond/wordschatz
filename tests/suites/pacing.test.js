группа('Разнообразие заданий', () => {

    /*
     * Владелец увидел на закреплении всего два типа заданий и спросил,
     * не сузилось ли разнообразие. Не сузилось — его столько и было:
     * из семи типов этапа четыре зависят от данных карточки, а «вставить
     * слово» и «собрать предложение» требуют примера. Существительное
     * без примера давало ровно два типа, фраза — один.
     */

    const доступные = (w) => {
        const v = ['translation_de_ru', 'translation_ru_de', 'match_pairs'];
        if (w.gender) v.push('article');
        if (w.type === 'verb' && w.preterite) v.push('verb_form');
        if (w.example_de) v.push('fill_blanks', 'sentence_builder');
        v.push('translation_ru_de_input');
        if (w.type === 'adjective') v.push('adjective_ending');
        return v;
    };

    const пул = (w) => доступные(w).filter(m => exercises.STAGES[exercises.getStage(w)].includes(m));

    const безПримера = { word: 'die Tür', type: 'noun', gender: 'die', repetitions: 5, mastery: 45 };
    const сПримером = { ...безПримера, example_de: 'Die Tür ist zu.' };

    тест('пример в карточке добавляет два типа заданий', () => {
        // «Вставить слово» и «собрать предложение» — оба про пример.
        // Это половина того, что вообще доступно существительному
        проверить.равно(пул(сПримером).length, пул(безПримера).length + 2,
            `без примера ${пул(безПримера).join(', ')} · с примером ${пул(сПримером).join(', ')}`);
    });

    тест('без примера всё равно есть из чего выбрать', () => {
        // Ради этого в закрепление добавлен match_pairs: он не требует
        // от карточки ничего, кроме соседей по словарю
        проверить.истина(пул(безПримера).length >= 3, `типов: ${пул(безПримера).join(', ')}`);
    });

    тест('фраза без примера тоже получает больше одного типа', () => {
        const фраза = { word: 'Guten Tag', type: 'phrase', repetitions: 5, mastery: 45 };
        проверить.истина(пул(фраза).length >= 2, `типов: ${пул(фраза).join(', ')}`);
    });

    тест('тот же тип подряд не повторяется', () => {
        const слово = { ...безПримера, lastMode: 'article' };
        for (let i = 0; i < 30; i++) {
            проверить.истина(exercises.pickByStage(слово, доступные(слово)) !== 'article',
                'прошлый тип должен исключаться');
        }
    });

    тест('когда выбора нет — повтор честен', () => {
        // Единственный доступный тип исключать некуда
        const слово = { word: 'Guten Tag', type: 'phrase', repetitions: 5, mastery: 45,
                        lastMode: 'translation_ru_de' };
        проверить.равно(exercises.pickByStage(слово, ['translation_ru_de']), 'translation_ru_de');
    });
});

группа('Потолок держит измеренный спрос', () => {

    /*
     * Число «тринадцать норм» получено прогоном, а не выведено на
     * бумаге. Бумажный расчёт по ступеням интервала давал восемь и был
     * неполон: он не учитывал лестницу заучивания и провалы.
     *
     * Поэтому проверка тоже гоняет, а не утверждает. Часы подменяются:
     * srs.calculate берёт Date.now(), и без подмены все сроки съезжают
     * в одну кучу — на этом я уже обжёгся, получив «спрос 28 норм».
     */

    const прогон = (норма, дней, точность) => {
        const ДЕНЬ = 86400000;
        const настоящее = Date.now;
        const начало = настоящее.call(Date);
        let часы = начало;
        Date.now = () => часы;

        try {
            const слова = [];
            const спрос = [];
            let seed = 7;
            const рнд = () => {
                seed = (seed * 1103515245 + 12345) % 2147483648;
                return seed / 2147483648;
            };

            for (let d = 0; d < дней; d++) {
                часы = начало + d * ДЕНЬ + 12 * 3600000;
                const конецДня = начало + d * ДЕНЬ + 23 * 3600000;

                const готовы = слова.filter(w => w.nextReview <= конецДня);
                готовы.forEach(w => {
                    const верно = рнд() < точность;
                    srs.applyTo(w, верно ? 3 : 1);
                    masteryUtils.registerAnswer(w, верно);
                });

                for (let k = 0; k < норма; k++) {
                    const w = {
                        interval: 0, ease: srs.DEFAULT_EASE, phase: 'learning',
                        stepIndex: 0, repetitions: 0, recent: [], attempts: 0,
                        correct: 0, mastery: 0
                    };
                    srs.applyTo(w, 3);
                    masteryUtils.registerAnswer(w, true);
                    слова.push(w);
                }

                спрос.push({ повторений: готовы.length, слова: слова });
            }
            return спрос;
        } finally {
            Date.now = настоящее;
        }
    };

    тест('при точности 90 % потолок покрывает зрелый спрос', () => {
        for (const норма of [5, 10]) {
            const лог = прогон(норма, 365, 0.9);
            const хвост = лог.slice(-35);
            const среднее = хвост.reduce((s, x) => s + x.повторений, 0) / хвост.length;

            проверить.истина(
                scheduler.getReviewLimit(норма) >= среднее,
                `норма ${норма}: потолок ${scheduler.getReviewLimit(норма)}, спрос ${среднее.toFixed(0)}`
            );
        }
    });

    тест('прежние множители спрос не покрывали', () => {
        // Проверка держит вывод, ради которого потолок и меняли дважды
        const лог = прогон(10, 365, 0.9);
        const хвост = лог.slice(-35);
        const среднее = хвост.reduce((s, x) => s + x.повторений, 0) / хвост.length;

        проверить.истина(среднее > 10 * 5, 'пять норм — мало');
        проверить.истина(среднее > 10 * 8, `восемь норм — тоже мало: спрос ${среднее.toFixed(0)}`);
    });

    тест('лёгкость не сползает вниз без остановки', () => {
        // Без возврата лёгкости средняя уезжала к нижней границе 1.3,
        // а вместе с ней разбухал и спрос
        const лог = прогон(10, 365, 0.9);
        const слова = лог[лог.length - 1].слова;
        const средняя = слова.reduce((s, w) => s + w.ease, 0) / слова.length;

        проверить.истина(средняя > 2.3, `средняя лёгкость ${средняя.toFixed(2)}`);
    });

    тест('доля трудных слов не растёт бесконечно', () => {
        const лог = прогон(10, 365, 0.9);
        const слова = лог[лог.length - 1].слова;
        const трудных = слова.filter(w => masteryUtils.isWeak(w)).length / слова.length;

        проверить.истина(трудных < 0.25, `трудных ${Math.round(трудных * 100)} %`);
    });
});

/*
 * Потолок повторений не падает вместе с автоснижением нормы.
 *
 * Защита от завала работала наоборот задуманного. Потолок считался от
 * действующей нормы, автоснижение опускало её с 10 до 5 — и потолок
 * падал со 140 до 70 ровно тогда, когда очередь и без того не
 * помещалась. Приложение сужало трубу, которую надо было расширить.
 *
 * Замер до правки: при точности 90 % очередь росла с двух слов до сорока
 * девяти, а при 88 % — до четырёхсот с лишним и дальше. После правки при
 * тех же 88 % очередь ноль.
 */
группа('Автоснижение нормы не режет потолок', () => {

    /** Выполнить с подменёнными настройками и вернуть как было. */
    const сНастройками = (пары, тело) => {
        const было = {};
        for (const ключ of Object.keys(пары)) было[ключ] = localStorage.getItem(`ws_${ключ}`);
        for (const [ключ, значение] of Object.entries(пары)) localStorage.setItem(`ws_${ключ}`, значение);
        try { return тело(); } finally {
            for (const [ключ, значение] of Object.entries(было)) {
                if (значение === null) localStorage.removeItem(`ws_${ключ}`);
                else localStorage.setItem(`ws_${ключ}`, значение);
            }
        }
    };

    тест('выбранная норма живёт отдельно от действующей', () => {
        сНастройками({ daily_goal: '5', chosen_goal: '10' }, () => {
            const профиль = config.getProfile();
            проверить.равно(профиль.dailyGoal, 5, 'действующая норма');
            проверить.равно(профиль.chosenGoal, 10, 'выбранная норма');
        });
    });

    тест('без выбранной нормы берётся действующая', () => {
        // Старые установки ключа не имеют — они не должны остаться без потолка
        сНастройками({ daily_goal: '15', chosen_goal: null }, () => {
            localStorage.removeItem('ws_chosen_goal');
            проверить.равно(config.getProfile().chosenGoal, 15);
        });
    });

    тест('потолок считается от выбранной, а не от урезанной', () => {
        сНастройками({ daily_goal: '5', chosen_goal: '10' }, () => {
            const профиль = config.getProfile();

            проверить.равно(scheduler.getReviewLimit(профиль.chosenGoal), 140, 'потолок должен остаться прежним');
            проверить.равно(scheduler.getReviewLimit(профиль.dailyGoal), 70, 'а от урезанной он был бы вдвое меньше');
        });
    });

    тест('при точности 85 % очередь не растёт без предела', () => {
        /*
         * Раньше этот случай расходился: спрос семьсот с лишним слов в
         * день при потолке семьдесят. Теперь новые слова приходят реже
         * (норма снижена), а разбирать по-прежнему дают сто сорок.
         */
        const ДЕНЬ = 86400000;
        const настоящее = Date.now;
        const начало = настоящее.call(Date);
        let часы = начало;
        Date.now = () => часы;

        try {
            const слова = [];
            let seed = 7;
            const рнд = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };

            const выбранная = 10;
            const потолок = scheduler.getReviewLimit(выбранная);   // от выбранной, не от текущей
            let норма = выбранная, серия = 0;
            let последняяОчередь = 0;

            for (let d = 0; d < 365; d++) {
                часы = начало + d * ДЕНЬ + 12 * 3600000;
                const конецДня = начало + d * ДЕНЬ + 23 * 3600000;

                const готовы = слова.filter(w => w.nextReview <= конецДня);
                const вУрок = готовы.slice(0, потолок);
                последняяОчередь = готовы.length - вУрок.length;

                const решение = scheduler.overloadDecision({ postponed: последняяОчередь, goal: норма, streak: серия });
                серия = решение.streak;
                норма = решение.goal;

                вУрок.forEach(w => {
                    const верно = рнд() < 0.85;
                    srs.applyTo(w, верно ? 3 : 1);
                    masteryUtils.registerAnswer(w, верно);
                });

                for (let k = 0; k < норма; k++) {
                    const w = {
                        interval: 0, ease: srs.DEFAULT_EASE, phase: 'learning',
                        stepIndex: 0, repetitions: 0, recent: [], attempts: 0, correct: 0, mastery: 0
                    };
                    srs.applyTo(w, 3);
                    masteryUtils.registerAnswer(w, true);
                    слова.push(w);
                }
            }

            проверить.истина(последняяОчередь < 20, `к концу года очередь ${последняяОчередь} — расходится`);
        } finally {
            Date.now = настоящее;
        }
    });
});

