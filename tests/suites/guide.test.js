import { группа, тест, проверить } from '../runner.js';

/*
 * Справка «Как пользоваться».
 *
 * Проверять здесь стоит не текст — его читают глазами, — а те поломки,
 * которые глазами как раз не видны. Все три случались в родственном
 * приложении: блок с опечаткой в названии поля молча исчезает, живое
 * число с опечаткой в имени печатается фигурными скобками наружу, а
 * кнопка «открыть» с несуществующим экраном выглядит как рабочая и
 * не делает ничего.
 */

const { guideContent } = await import('../../js/i18n/guide.js');
const { guide } = await import('../../js/modules/guide.js');

/** Виды блоков, которые умеет рисовать modules/guide.js. */
const ВИДЫ = ['p', 'hint', 'example', 'sub', 'steps', 'rows', 'go'];

/** Все текстовые строки содержания, где могут быть подстановки и звёздочки. */
function всеСтроки() {
    const строки = [];

    for (const раздел of guideContent.sections) {
        строки.push(раздел.name);

        for (const блок of раздел.blocks) {
            if (блок.p) строки.push(блок.p);
            if (блок.hint) строки.push(блок.hint);
            if (блок.example) строки.push(блок.example);
            if (блок.sub) строки.push(блок.sub);
            if (блок.steps) строки.push(...блок.steps);
            if (блок.rows) for (const [имя, текст] of блок.rows) строки.push(имя, текст);
            if (блок.go) for (const [, подпись] of блок.go) строки.push(подпись);
        }
    }

    return строки;
}

группа('Справка: устройство содержания', () => {

    тест('каждый блок известного вида', () => {
        /*
         * Блок неизвестного вида не роняет экран и не пишет в консоль —
         * block() возвращает пустую строку, и абзац просто не появляется.
         * Заметить такое можно только сверяя справку с исходником, то
         * есть никогда.
         */
        const чужие = [];

        for (const раздел of guideContent.sections) {
            for (const блок of раздел.blocks) {
                const поля = Object.keys(блок);
                const свои = поля.filter(поле => ВИДЫ.includes(поле));

                if (свои.length !== 1 || поля.length !== 1) {
                    чужие.push(`${раздел.name}: {${поля.join(', ')}}`);
                }
            }
        }

        проверить.совпадает(чужие, [], 'блок должен иметь ровно одно поле известного вида');
    });

    тест('разделы непустые и названы по-разному', () => {
        const названия = guideContent.sections.map(с => с.name);

        проверить.истина(названия.length >= 5, 'разделов должно быть несколько');
        проверить.равно(new Set(названия).size, названия.length, 'названия разделов повторяются');

        for (const раздел of guideContent.sections) {
            проверить.истина(раздел.blocks?.length > 0, `раздел «${раздел.name}» пуст`);
        }
    });

    тест('открыт ровно один раздел, и это первый', () => {
        // Развёрнутые целиком разделы дают полотно в несколько экранов;
        // свёрнутые — оглавление. Открытый первый отвечает на «с чего начать»
        const открытые = guideContent.sections.filter(с => с.open);

        проверить.равно(открытые.length, 1, 'открытым должен быть один раздел');
        проверить.равно(открытые[0], guideContent.sections[0], 'открыт должен быть первый');
    });

    тест('кнопки «открыть» ведут на настоящие экраны', async () => {
        /*
         * Опечатка в названии экрана даёт кнопку, которая нажимается и
         * показывает заглушку «раздел в разработке». Список маршрутов
         * читаем из самого app.js, а не переписываем сюда: переписанный
         * разошёлся бы с настоящим при первом же новом экране.
         */
        const код = await (await fetch('../js/app.js')).text();
        const маршруты = new Set(
            [...код.matchAll(/viewId === '(\w+)'/g)].map(m => m[1])
        );

        проверить.истина(маршруты.has('plan'), 'маршруты из app.js не прочитались');

        const мимо = [];
        for (const раздел of guideContent.sections) {
            for (const блок of раздел.blocks) {
                if (!блок.go) continue;
                for (const [экран] of блок.go) {
                    if (!маршруты.has(экран)) мимо.push(`${раздел.name}: ${экран}`);
                }
            }
        }

        проверить.совпадает(мимо, [], 'в справке кнопки на несуществующие экраны');
    });
});

группа('Справка: живые числа и выделение', () => {

    тест('все подстановки в тексте существуют', async () => {
        /*
         * Незнакомая подстановка остаётся в тексте как есть, и человек
         * читает «норма — {норма} в день». Ровно ради этого числа и
         * заводились: выдуманные стареют молча, а сломанные — громко и
         * стыдно.
         */
        const факты = await guide.facts();
        const известные = new Set(Object.keys(факты));

        проверить.истина(известные.size > 0, 'facts() ничего не вернул');

        const чужие = new Set();
        for (const строка of всеСтроки()) {
            // \p{L}, а не \w: имена подстановок русские, а \w в JavaScript
            // это только латиница. Проверка, написанная через \w, не нашла
            // бы даже сломанную подстановку — она их вообще не видит
            for (const m of String(строка).matchAll(/\{([\p{L}\p{N}_]+)\}/gu)) {
                if (!известные.has(m[1])) чужие.add(m[1]);
            }
        }

        проверить.совпадает([...чужие], [], 'в тексте справки неизвестные подстановки');
    });

    тест('после подстановки скобок не остаётся', async () => {
        const факты = await guide.facts();

        for (const строка of всеСтроки()) {
            const готово = guide.markup(строка, факты);
            проверить.ложь(/\{[\p{L}\p{N}_]+\}/u.test(готово), `осталась подстановка: ${готово}`);
        }
    });

    тест('живые числа — строки, а не «undefined»', async () => {
        const факты = await guide.facts();

        for (const [ключ, значение] of Object.entries(факты)) {
            проверить.равно(typeof значение, 'string', `${ключ} должен быть строкой`);
            проверить.истина(значение.length > 0, `${ключ} пуст`);
            проверить.ложь(значение.includes('undefined'), `${ключ}: ${значение}`);
            проверить.ложь(значение.includes('NaN'), `${ключ}: ${значение}`);
        }
    });

    тест('форма числа для слов согласуется', async () => {
        // «1 слово», «2 слова», «5 слов» — на телефоне это первое, что
        // видит человек в примере, и «5 слово» портит впечатление сразу
        const формы = guideContent.words;
        проверить.истина(!!(формы.one && формы.few && формы.many), 'нет форм числа');
        проверить.содержит(формы.one, '{count}');
        проверить.содержит(формы.many, '{count}');
    });

    тест('звёздочки превращаются в выделение, а не печатаются', () => {
        const готово = guide.markup('нажмите *НАЧАТЬ УРОК* и всё', {});

        проверить.содержит(готово, '<b');
        проверить.содержит(готово, 'НАЧАТЬ УРОК');
        проверить.ложь(готово.includes('*'), 'звёздочка осталась в тексте');
    });

    тест('разметка из текста остаётся текстом', () => {
        /*
         * Справку правят как текст, и однажды в ней окажется угловая
         * скобка — в примере, в названии клавиши, в чужой цитате.
         * Экранирование идёт до раскрытия звёздочек, поэтому свои теги
         * ставятся, а чужие нет.
         */
        const готово = guide.markup('нажмите <b>сюда</b> и *туда*', {});

        проверить.содержит(готово, '&lt;b&gt;');
        проверить.равно((готово.match(/<b/g) || []).length, 1, 'должен быть ровно один свой тег');
    });

    тест('подставленное значение тоже экранируется', () => {
        // Числа приходят из базы, а туда попадает всё что угодно —
        // включая слово с угловой скобкой в переводе
        const готово = guide.markup('в словаре {слов}', { слов: '<img src=x>' });

        проверить.ложь(готово.includes('<img'), 'значение подставилось разметкой');
        проверить.содержит(готово, '&lt;img');
    });
});

группа('Справка: отрисовка', () => {

    тест('блок каждого вида даёт разметку', () => {
        const образцы = [
            { p: 'абзац' },
            { hint: 'приписка' },
            { example: 'пример' },
            { sub: 'подзаголовок' },
            { steps: ['раз', 'два'] },
            { rows: [['имя', 'пояснение']] },
            { go: [['room', 'Комната']] }
        ];

        for (const образец of образцы) {
            const вид = Object.keys(образец)[0];
            const разметка = guide.block(образец, {});
            проверить.истина(разметка.length > 0, `вид «${вид}» ничего не нарисовал`);
        }
    });

    тест('неизвестный вид не роняет отрисовку', () => {
        проверить.равно(guide.block({ чтоТоНовое: 'текст' }, {}), '');
    });

    тест('раздел рисуется гармошкой с нужным классом', () => {
        const разметка = guide.section(guideContent.sections[0], {});

        // Класс guide-part держит на себе стрелку и цвет открытого
        // раздела — без него гармошка остаётся, а вид теряется
        проверить.содержит(разметка, 'class="guide-part');
        проверить.содержит(разметка, '<summary');
        проверить.содержит(разметка, 'open');
    });

    тест('свёрнутый раздел не помечен открытым', () => {
        const свёрнутый = guideContent.sections.find(с => !с.open);
        const разметка = guide.section(свёрнутый, {});

        проверить.ложь(/<details[^>]*\sopen/.test(разметка), 'раздел открыт, хотя не должен');
    });
});
