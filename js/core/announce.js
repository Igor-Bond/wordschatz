/**
 * Короткие сообщения для экранного чтеца.
 *
 * Приложение перерисовывает содержимое целиком: сменился экран — в
 * `#main-content` встала новая разметка. Зрячий это видит, чтец — нет:
 * такие подмены он не объявляет, и человек остаётся без ответа на
 * вопрос «что сейчас произошло». То же с ответом на задание: подсветка
 * кнопки зелёным ничего не сообщает тому, кто её не видит.
 *
 * Поэтому здесь одна живая область на весь документ, куда кладётся
 * фраза. Чтец читает её сам, вслух, не сбивая фокус.
 */

/** Пустая строка между сообщениями: иначе повтор того же текста молчит. */
let последнее = '';

export const announce = {

    say: (текст) => {
        const область = document.getElementById('a11y-live');
        if (!область || !текст) return;

        // Два одинаковых сообщения подряд — обычное дело: два верных
        // ответа подряд. Без сброса чтец второй раз промолчит, потому
        // что содержимое области не изменилось
        if (текст === последнее) область.textContent = '';

        последнее = текст;

        // Пауза нужна, чтобы чтец заметил именно изменение, а не застал
        // область уже заполненной при первом обходе
        requestAnimationFrame(() => { область.textContent = текст; });
    },

    clear: () => {
        const область = document.getElementById('a11y-live');
        if (область) область.textContent = '';
        последнее = '';
    }
};
