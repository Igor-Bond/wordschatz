import { config } from '../config.js';

/**
 * Сколько времени займёт урок.
 *
 * На плане стоит число заданий — «НАЧАТЬ УРОК (88)», — и по нему нельзя
 * понять, десять это минут или сорок. При этом в настройках норма
 * подписана именно временем: «~27 мин в день». Обещание есть, а на
 * экране, где решают садиться или нет, его не видно.
 *
 * Считается по вашей собственной скорости, а не по среднему человеку.
 * После каждого урока сюда приходит длительность и число заданий, и
 * оценка подтягивается к настоящему темпу. До первого урока берётся
 * значение по умолчанию — оно же выведено из подписи «~27 мин»: при
 * зрелой нагрузке в полторы сотни припоминаний это около одиннадцати
 * секунд на задание.
 */
export const pace = {

    /** Ключ в настройках. Не в профиле: скорость своя на каждом устройстве. */
    KEY: 'pace_seconds',

    /** Пока своих замеров нет. Выведено из подписи «~27 мин» у нормы 10. */
    DEFAULT_SECONDS: 11,

    /**
     * Границы правдоподобия для одного замера.
     *
     * Урок можно свернуть на середине и вернуться к нему через сутки —
     * тогда «время на задание» выйдет в часах и испортит оценку надолго.
     * Снизу тоже нужна граница: если урок как-то промотали за секунду,
     * это не темп, а сбой.
     */
    MIN_SECONDS: 2,
    MAX_SECONDS: 60,

    /**
     * Насколько новый замер сдвигает оценку.
     *
     * Треть — компромисс между «оценка скачет после одного медленного
     * урока» и «оценка не поспевает за тем, как человек разгоняется».
     * За три-четыре урока подстраивается почти полностью.
     */
    SMOOTHING: 0.3,

    /**
     * Есть ли собственные замеры.
     *
     * Нужно подписи под кнопкой: обещать «по вашей скорости» до первого
     * урока — вранье, пусть и мелкое. Пока замеров нет, так и говорим.
     */
    measured: () => {
        const записано = parseFloat(config.get(pace.KEY));
        return Number.isFinite(записано) && записано > 0;
    },

    /** Нынешняя оценка секунд на задание. */
    perItem: () => {
        const записано = parseFloat(config.get(pace.KEY));
        if (!Number.isFinite(записано) || записано <= 0) return pace.DEFAULT_SECONDS;
        return Math.min(pace.MAX_SECONDS, Math.max(pace.MIN_SECONDS, записано));
    },

    /**
     * Учесть прошедший урок.
     *
     * @param {number} items сколько заданий было
     * @param {number} ms сколько заняло
     * @returns {number|null} новая оценка или null, если замер отброшен
     */
    record: (items, ms) => {
        if (!(items > 0) || !(ms > 0)) return null;

        const наЗадание = ms / 1000 / items;

        // Замер вне границ правдоподобия не усредняем, а выбрасываем:
        // подрезать его до границы значило бы всё равно поверить ему
        if (наЗадание < pace.MIN_SECONDS || наЗадание > pace.MAX_SECONDS) return null;

        const прежний = parseFloat(config.get(pace.KEY));
        const новый = Number.isFinite(прежний) && прежний > 0
            ? прежний + (наЗадание - прежний) * pace.SMOOTHING
            : наЗадание;

        const итог = Math.round(новый * 10) / 10;
        config.set(pace.KEY, String(итог));
        return итог;
    },

    /**
     * Сколько припоминаний в уроке.
     *
     * Не то же, что число слов в плане. Слово из повторения спрашивают
     * один раз — карточкой, если оно трудное, иначе заданием. А новое
     * слово проходит дважды: карточка показывает, задание спрашивает.
     */
    itemsInLesson: (plan) => (plan?.review?.length || 0) + (plan?.newWords?.length || 0) * 2,

    /** Оценка урока в минутах, не меньше одной. */
    estimateMinutes: (items) => {
        if (!(items > 0)) return 0;
        return Math.max(1, Math.round(items * pace.perItem() / 60));
    }
};
