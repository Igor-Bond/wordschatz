/**
 * Высота приложения: следим, чтобы страница совпадала с видимой областью.
 *
 * Приложение занимает ровно экран — тело не прокручивается, нижнее меню
 * прижато к низу через absolute. Держится это на `height: 100dvh`, и в
 * норме единица работает правильно. Но на Android после перезагрузки из
 * самого приложения (кнопка «Обновить» → SKIP_WAITING → location.reload)
 * значение иногда остаётся посчитанным для скрытой панели браузера:
 * страница выходит выше экрана, от меню видна одна кромка, и лечит это
 * только сворачивание — то есть событие resize.
 *
 * Первая попытка чинить это была грубее: высота всегда бралась из
 * window.innerHeight. На iPhone получилось хуже исходного — под меню
 * появилась пустая полоса, потому что на старте innerHeight там ещё не
 * учитывает безопасные зоны, а второго события не приходит.
 *
 * Поэтому здесь измерение, а не замена. Скрытая проба ростом 100dvh
 * сравнивается с настоящей высотой окна: совпало — не вмешиваемся и
 * оставляем dvh работать; разошлось — подставляем измеренное значение.
 * Разъехавшаяся высота чинится сама, а верная не портится.
 */

/**
 * Насколько разрешено расходиться, прежде чем вмешиваться.
 *
 * Небольшая разница между dvh и окном — обычное дело: безопасные зоны,
 * округления, полоса жестов. Вмешательство там приносит вред — на iPhone
 * под меню появлялась пустая полоса, на Android снизу проступала белая.
 * Настоящая поломка, ради которой всё затевалось, выглядит иначе:
 * застрявший dvh отличается на высоту панели браузера, а это заметно
 * больше полусотни точек.
 */
const ДОПУСК = 24;

/**
 * iPhone и iPad: у них движок один на все браузеры, и разница окна с
 * экраном означает у них не то же, что у остальных.
 */
const этоIOS = () => /iPad|iPhone|iPod/.test(navigator.userAgent || '')
    || (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);

/**
 * Наибольший разумный сдвиг меню вниз.
 *
 * Строка состояния iPhone — 59 точек, у моделей постарше меньше. Всё,
 * что больше сотни, разницей строки состояния уже не объясняется, и
 * двигать туда меню вслепую опаснее, чем не двигать вовсе.
 */
const ПРЕДЕЛ_СДВИГА = 100;

let проба = null;

function пробнаяВысота() {
    if (!проба) {
        проба = document.createElement('div');
        проба.setAttribute('aria-hidden', 'true');
        проба.style.cssText = 'position:fixed;top:0;left:0;width:0;height:100dvh;visibility:hidden;pointer-events:none';
        document.body.appendChild(проба);
    }
    return проба.getBoundingClientRect().height;
}

export const viewport = {

    apply: () => {
        const окно = window.innerHeight;
        if (!окно || !document.body) return;

        const dvh = пробнаяВысота();

        // dvh справляется сам — не мешаем. Заодно снимаем подстановку,
        // если она осталась с того момента, когда мешал
        if (!dvh || Math.abs(dvh - окно) <= ДОПУСК) {
            if (document.documentElement.style.getPropertyValue('--app-height')) {
                document.documentElement.style.removeProperty('--app-height');
            }
            return;
        }

        // Сравниваем с тем, что реально стоит в переменной, а не с
        // запомненным числом: иначе однажды разъехавшееся значение так и
        // осталось бы — событие пришло, но «высота та же», и выхода нет
        if (document.documentElement.style.getPropertyValue('--app-height') === `${окно}px`) return;

        document.documentElement.style.setProperty('--app-height', `${окно}px`);
    },

    /**
     * Что за полоса экрана остаётся ниже разметочной области — и наша ли.
     *
     * Разница между экраном и окном сама по себе не говорит ничего: она
     * бывает и там, где рисовать можно, и там, где нельзя, а выглядят
     * оба случая одинаково. Различать их по названию платформы — плохо:
     * правило «iPhone значит наше» держится на совпадении, а не на
     * причине, и однажды сломается молча.
     *
     * Причина же читается из самих чисел.
     *
     * Случай первый, iPhone с полупрозрачной строкой состояния: iOS
     * отдаёт окно высотой «экран минус строка состояния» и прижимает
     * его к верху. Подпись случая — разница в точности равна верхнему
     * полю: 852 − 793 = 59, и верхнее поле тоже 59. Совпадение не
     * случайное, это одна и та же величина, просто вычтенная из высоты
     * и не учтённая в положении. Рисовать туда можно: выяснилось
     * случайно, когда убрали тёмную подложку под меню и на айфоне
     * открылся провал — значит подложка его закрывала, значит пиксели
     * наши.
     *
     * Случай второй, Android: те же 55 точек — системная полоса жестов.
     * Верхнее поле с ними не совпадает, окно до них просто не доходит,
     * и опущенное туда меню пропадёт из виду. Красит их система, и
     * тёмными они выходят из-за `color-scheme: dark` и theme_color.
     *
     * Функция чистая: считает по переданным числам и ничего не трогает.
     * Поэтому её проверяют автоматические проверки, а не устройство.
     *
     * @returns {{зазор: number, наше: boolean, причина: string}}
     */
    probeBottom: ({ экран = 0, верх = 0, окно = 0, полеСверху = 0, встроенноеIOS = false }) => {
        const зазор = Math.round(экран - верх - окно);

        if (!(зазор > ДОПУСК)) return { зазор: Math.max(зазор, 0), наше: false, причина: 'нет' };
        if (зазор > ПРЕДЕЛ_СДВИГА) return { зазор, наше: false, причина: 'чужое' };

        // Подпись случая iOS: вычтено ровно верхнее поле. Двойка — на
        // округления, iOS отдаёт эти величины дробными
        const этоСтрокаСостояния = встроенноеIOS
            && полеСверху > 0
            && Math.abs(зазор - полеСверху) <= 2;

        return этоСтрокаСостояния
            ? { зазор, наше: true, причина: 'строка состояния' }
            : { зазор, наше: false, причина: 'системная полоса' };
    },

    /** Замеры для probeBottom, снятые с настоящего окна. */
    measureBottom: () => {
        const проба = document.createElement('div');
        проба.setAttribute('aria-hidden', 'true');
        проба.style.cssText = 'position:fixed;top:0;padding-top:env(safe-area-inset-top);visibility:hidden;pointer-events:none';
        document.body.appendChild(проба);
        const полеСверху = parseInt(getComputedStyle(проба).paddingTop) || 0;
        проба.remove();

        return viewport.probeBottom({
            экран: (window.screen && window.screen.height) || 0,
            верх: Number.isFinite(window.screenY) ? window.screenY : 0,
            окно: window.innerHeight,
            полеСверху: полеСверху,
            встроенноеIOS: этоIOS() && navigator.standalone === true
        });
    },

    /**
     * Меню больше не опускается ниже разметочной области.
     *
     * Была затея сдвигать его в те 59 точек, которые остаются под окном
     * на iPhone: доказательством служило то, что подложка меню их
     * закрашивает — значит пиксели наши. Вывод оказался неполным.
     * Рисовать туда страница действительно умеет, а вот **касания
     * туда не доходят**: событий за нижней границей разметочной области
     * браузер не отдаёт.
     *
     * На деле это выглядело так: меню опустилось на 59 точек, кнопки
     * высотой 76 — и нажималась у них одна верхняя кромка. Владелец так
     * и сообщил: «кнопки реагируют только по верхней кромке».
     *
     * Рисовать можно ≠ нажимать можно. Сдвиг снят; зазор под меню
     * закрывает подложка, а по-настоящему лечит его метка строки
     * состояния `black` в index.html — она переносит само окно вниз,
     * вместе с областью касаний.
     */
    pinNav: () => {
        const корень = document.documentElement;
        if (корень.style.getPropertyValue('--nav-drop')) {
            корень.style.removeProperty('--nav-drop');
        }
    },

    /** Обе поправки разом — высота страницы и посадка меню. */
    refresh: () => {
        viewport.apply();
        viewport.pinNav();
    },

    init: () => {
        viewport.refresh();

        // На iPhone размеры на момент DOMContentLoaded ещё не окончательные:
        // безопасные зоны применяются позже, а второго события может и не
        // быть. Поэтому перемеряем несколько раз после запуска
        requestAnimationFrame(viewport.refresh);
        window.addEventListener('load', viewport.refresh);
        setTimeout(viewport.refresh, 300);
        setTimeout(viewport.refresh, 1000);

        // resize приходит при повороте, смене панели браузера и клавиатуре;
        // orientationchange на части устройств опережает resize и даёт
        // старое значение — поэтому пересчитываем ещё и следующим кадром
        window.addEventListener('resize', viewport.refresh);
        window.addEventListener('orientationchange', () => {
            viewport.refresh();
            requestAnimationFrame(viewport.refresh);
            setTimeout(viewport.refresh, 250);
        });

        // Возврат из фонового кэша браузера: разметка та же, размеры новые
        window.addEventListener('pageshow', viewport.refresh);

        // Разворачивание свёрнутого приложения — тот самый случай, который
        // раньше приходилось делать руками, чтобы меню встало на место
        document.addEventListener('visibilitychange', () => {
            if (document.visibilityState === 'visible') viewport.refresh();
        });

        // Экранная клавиатура и панель браузера двигают видимую область,
        // не вызывая resize в части браузеров
        window.visualViewport?.addEventListener('resize', viewport.refresh);
    }
};
