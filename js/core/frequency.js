/**
 * Насколько часто слово встречается в живой речи (§4, §5 ТЗ).
 *
 * Зачем. Набор слов придумывает языковая модель, и внутри одной темы
 * «Быт» рядом оказываются «дверь» и «стиральная машина». Первое человек
 * услышит в первый же день, второе — может быть, через год. Времени у
 * него столько же, и тратить его поровну — расточительство.
 *
 * Список лежит в vendor/frequency-de.js и подключается по требованию:
 * 124 КБ незачем разбирать тем, кто просто открыл приложение повторить
 * вчерашнее. Первое обращение стоит около десяти миллисекунд, дальше
 * ответы мгновенные.
 *
 * Чего список не умеет: он собран по субтитрам и состоит из тех форм,
 * какие встретились. «Tisch» в нём есть, «Tische» — отдельной строкой и
 * ниже. Мы ищем по начальной форме карточки, и на настоящем наборе это
 * даёт 94 попадания из ста; промахи — составные термины вроде
 * «Mikroelektronik», которые и правда редки.
 */

let ранги = null;
let загрузка = null;

/**
 * Границы полос.
 *
 * Тысяча — то, без чего нельзя говорить вообще. Пять тысяч примерно
 * покрывают бытовую речь. Всё, что ниже пятнадцатой тысячи, редко
 * настолько, что точный номер уже не важен.
 */
export const BANDS = [
    { key: 'core', upTo: 1000 },
    { key: 'common', upTo: 5000 },
    { key: 'rare', upTo: Infinity }
];

export const frequency = {

    /** Загружен ли список: интерфейсу нужно знать, ждать ли. */
    get ready() {
        return ранги !== null;
    },

    /**
     * Подключение списка. Повторные вызовы возвращают ту же работу —
     * иначе десять карточек подряд запустили бы десять разборов.
     */
    load: async () => {
        if (ранги) return ранги;
        if (загрузка) return загрузка;

        загрузка = (async () => {
            const { FREQUENCY_LIST } = await import('../../vendor/frequency-de.js');

            const карта = new Map();
            const слова = FREQUENCY_LIST.split('\n');
            for (let i = 0; i < слова.length; i++) {
                const слово = слова[i];
                if (слово) карта.set(слово, i + 1);
            }

            ранги = карта;
            загрузка = null;
            return ранги;
        })();

        return загрузка;
    },

    /**
     * Начальная форма для поиска: без артикля, без возвратного «sich»,
     * в нижнем регистре. Составные записи вроде «warten auf» ищем по
     * первому слову — именно оно несёт значение.
     */
    normalise: (word) => String(word ?? '')
        .trim()
        .replace(/^(der|die|das)\s+/i, '')
        .replace(/^sich\s+/i, '')
        .split(/\s+/)[0]
        .replace(/[^\p{L}]/gu, '')
        .toLowerCase(),

    /**
     * Место слова в списке или null, если его там нет.
     * Список должен быть загружен: без него честнее вернуть null, чем
     * заставлять отрисовку ждать.
     */
    rank: (word) => {
        if (!ранги) return null;

        const ключ = frequency.normalise(word);
        return ключ ? (ранги.get(ключ) ?? null) : null;
    },

    /**
     * Полоса частотности: 'core' | 'common' | 'rare' | 'unknown'.
     * Отсутствие в списке — тоже ответ, и означает он «очень редкое».
     */
    band: (word) => {
        const место = frequency.rank(word);
        if (место === null) return 'unknown';

        return BANDS.find(b => место <= b.upTo).key;
    },

    /**
     * Сортировка по частоте: частые вперёд, неизвестные в конец.
     * Порядок внутри одинаковых мест сохраняется — сортировка устойчива.
     */
    sort: (words, ключ = (w) => w.word) => [...words].sort((a, b) => {
        const ra = frequency.rank(ключ(a)) ?? Infinity;
        const rb = frequency.rank(ключ(b)) ?? Infinity;
        return ra - rb;
    }),

    /**
     * Сводка по набору — то, что показывается перед утверждением темы.
     * Человек решает, брать ли набор, и ему нужно одно число: сколько
     * здесь слов, которые действительно встретятся.
     */
    summarise: (words, ключ = (w) => w.word) => {
        const счёт = { core: 0, common: 0, rare: 0, unknown: 0 };
        for (const w of words) счёт[frequency.band(ключ(w))]++;

        return {
            ...счёт,
            полезных: счёт.core + счёт.common,
            всего: words.length
        };
    }
};
